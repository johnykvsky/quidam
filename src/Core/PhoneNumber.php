    /** @var list<string> IMEI reporting body identifiers (first 2 digits) */
    protected const array IMEI_REPORTING_BODIES = ['35', '86', '01', '99'];

    public function __construct(
        protected readonly RandomizerInterface $randomizer,
        protected readonly StringsExtensionInterface $strings,
        protected readonly LuhnCalculatorInterface $luhn,
        protected readonly LocaleInterface $locale,
    ) {
    }

    /**
     * National (landline) number as written locally, e.g. "020 7946 0000" - sample format without country by default
     */
    public function phoneNumber(): string
    {
        return $this->strings->numerify($this->randomizer->randomElement(static::FORMATS));
    }

    /**
     * National mobile number as written locally, e.g. "0712 345678"
     */
    public function mobilePhoneNumber(): string
    {
        return $this->strings->numerify($this->randomizer->randomElement(static::MOBILE_FORMATS));
    }

    /**
     * Number with country calling code, as written internationally, e.g. "+44 20 7946 0000" - built from a national
     * (landline or mobile) number of the locale; a random real country and digits when locale has no calling code
     */
    public function internationalPhoneNumber(): string
    {
        $callingCode = $this->locale->callingCode();

        if ($callingCode === null) {
            [$callingCode, $digits] = $this->randomE164();

            // groups of 3, a single digit left at the end joins the last group ("342 3" -> "3423")
            return '+' . $callingCode . ' ' . preg_replace('/(^| )(\d{3}) (\d)$/', '$1$2$3', implode(' ', str_split($digits, 3)));
        }

        return '+' . $callingCode . ' ' . $this->withoutTrunkPrefix($this->nationalNumber());
    }

    /**
     * Phone number in E.164 format, e.g. "+48123456789" - of the locale country, a random real country when locale
     * has no calling code. With $countryCode (ISO 3166-1 alpha-2, e.g. "PL") of that country - national formats of
     * the locale when it's the locale country, otherwise calling code and number of digits of that country.
     *
     * @throws InvalidArgumentException when the country is unknown or has no own calling code
     */
    public function e164PhoneNumber(?string $countryCode = null): string
    {
        if ($countryCode !== null && $countryCode !== $this->locale->countryCode()) {
            return '+' . implode('', $this->countryE164($countryCode));
        }

        $callingCode = $this->locale->callingCode();

        if ($callingCode === null) {
            return '+' . implode('', $this->randomE164());
        }

        return '+' . $callingCode . preg_replace('/\D/', '', $this->withoutTrunkPrefix($this->nationalNumber()));
    }

    /**
     * 15-digit IMEI (device identifier) with valid Luhn check digit, e.g. "356938035643809"
     */
    public function imei(): string
    {
        $number = $this->randomizer->randomElement(static::IMEI_REPORTING_BODIES) . $this->strings->numerify('############');

        return $number . $this->luhn->checkDigit($number);
    }

    /**
     * Landline or mobile national number
     */
    protected function nationalNumber(): string
    {
        return $this->randomizer->getBool() ? $this->phoneNumber() : $this->mobilePhoneNumber();
    }

    /**
     * National number without the trunk prefix ("020 7946 0000" -> "20 7946 0000") - as dialled from abroad
     */
    protected function withoutTrunkPrefix(string $number): string
    {
        $trunkPrefix = $this->locale->trunkPrefix();

        return $trunkPrefix !== '' && str_starts_with($number, $trunkPrefix) ? ltrim(substr($number, strlen($trunkPrefix))) : $number;
    }

    /**
     * Calling code and subscriber digits of a random real country
     *
     * @return array{string, string}
     */
    protected function randomE164(): array
    {
        return $this->e164FromFormat($this->randomizer->randomElement(static::E164_FORMATS));
    }

    /**
     * Calling code and subscriber digits of given country
     *
     * @return array{string, string}
     */
    protected function countryE164(string $countryCode): array
    {
        $callingCode = static::COUNTRY_CALLING_CODES[$countryCode] ?? throw new InvalidArgumentException(sprintf(
            'Unknown country "%s" or it has no own calling code - expected ISO 3166-1 alpha-2 (uppercase), e.g. "PL"',
            $countryCode,
        ));

        foreach (static::E164_FORMATS as $format) {
            if (str_starts_with($format, '+' . $callingCode . ' ')) {
                return $this->e164FromFormat($format);
            }
        }

        throw new InvalidArgumentException(sprintf('No E.164 format for calling code "%s" of country "%s"', $callingCode, $countryCode));
    }

    /**
     * Calling code and national number from an E.164 mask, e.g. "+48 %########", "+229 01########"
     *
     * @return array{string, string}
     */
    protected function e164FromFormat(string $format): array
    {
        [$callingCode, $mask] = explode(' ', substr($format, 1), 2);

        return [$callingCode, $this->strings->numerify($mask)];
    }
}
