    /**
     * ASCII approximation of text - ASCII characters are kept (including spaces and punctuation),
     * known characters are transliterated, unknown ones are removed
     */
    public function transliterate(string $text): string
    {
        if (!preg_match('/[^\x00-\x7F]/', $text)) {
            return $text;
        }

        return (string) preg_replace('/[^\x00-\x7F]/u', '', strtr($text, static::TABLE));
    }

    /**
     * Lowercase ASCII letters and digits, groups joined with $separator, e.g. "Żółta Łódź!" gives "zolta-lodz"
     */
    public function slug(string $text, string $separator = '-'): string
    {
        $slug = (string) preg_replace('/[^a-z0-9]+/', $separator, strtolower($this->transliterate($text)));

        return $separator === '' ? $slug : trim($slug, $separator);
    }
